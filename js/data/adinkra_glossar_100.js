window.mergeAdinkraGlossar = function () {
  const cat = window.ADINKRA_CATALOG || {};
  (window.ADINKRA_GLOSSAR_100 || []).forEach((row) => {
    if (!cat[row.id]) {
      cat[row.id] = {
        name: row.name,
        meaning: row.meaning,
        category: row.cat,
        glossar: row.n,
        glyph: '◈',
      };
    } else if (!cat[row.id].glossar) {
      cat[row.id].glossar = row.n;
    }
  });
  const aliases = {
    nkonsonnkonson: 'nkonsonkonson',
    ananse: 'ananse_ntentan',
    akoma_ntoso: 'akoma_ntoso',
    hwe_mu_dua: 'hwehwemudua',
  };
  Object.entries(aliases).forEach(([alias, canonical]) => {
    if (cat[canonical] && !cat[alias]) cat[alias] = { ...cat[canonical], aliasOf: canonical };
  });
  window.ADINKRA_CATALOG = cat;
};
